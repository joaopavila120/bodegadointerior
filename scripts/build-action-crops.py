"""Read sprite alpha to register frames. Does not alter or generate image pixels.
Asset tooling only: Python, Pillow, numpy and scipy; the game has no dependencies.
"""
from pathlib import Path
import json
import numpy as np
from PIL import Image
from scipy.ndimage import label, find_objects

ROOT = Path(__file__).resolve().parents[1]
DOGS = {'cusco', 'baia'}
BEASTS = {'coral', 'teiu', 'ourico', 'corposeco'}
result = {}
for path in sorted((ROOT / 'assets/images/actions').glob('*-v1.png')):
    key = path.stem[:-3]
    image = Image.open(path)
    alpha = np.array(image)[:, :, 3]
    labels, _ = label(alpha > 100)
    sizes = np.bincount(labels.ravel())
    boxes = []
    for ident, region in enumerate(find_objects(labels), 1):
        if sizes[ident] <= 2000:
            continue
        y, x = region
        boxes.append([x.start, y.start, x.stop, y.stop])
    count = 16 if key in DOGS else 8 if key in BEASTS else 12
    assert len(boxes) == count, (key, len(boxes), 'Inspect separated poses before registering')
    boxes.sort(key=lambda box: box[1])
    frames = []
    for row in range(count // 4):
        for left, top, right, bottom in sorted(boxes[row*4:row*4+4]):
            # Register at the hips, not at the tip of a changing spear / gun.
            height = bottom - top
            strip = alpha[top + int(height * .64):top + int(height * .78), left:right] > 140
            weights = strip.sum(axis=0)
            pivot = left + int(np.searchsorted(weights.cumsum(), weights.sum() / 2))
            if key in DOGS | BEASTS:
                pivot = (left + right) // 2
            x, y = max(0, left-2), max(0, top-2)
            w, h = min(image.width, right+2)-x, min(image.height, bottom+2)-y
            frames.append([x, y, w, h, pivot-x, bottom-y])
    reference = {'lanceiro': 286, 'sepe': 316}.get(key, frames[0][3]-4)
    if key in {'coral', 'teiu'}:
        reference = frames[0][2]-4
    result[key] = {'size': list(image.size), 'reference': reference, 'frames': frames}

out = ROOT / 'js/render/action-art-crops.js'
out.write_text('// Reviewed alpha bounds and hip/ground anchors. Generated by scripts/build-action-crops.py.\n'
               "'use strict';\nconst ACTION_ART_CROPS = " + json.dumps(result, ensure_ascii=False, indent=2) + ';\n', encoding='utf-8')
print(f'{len(result)} sheets, {sum(len(v["frames"]) for v in result.values())} registered frames')
