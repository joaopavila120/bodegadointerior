"""Read sprite alpha and emit crop coordinates; never modify generated PNGs."""
import json
from pathlib import Path
from PIL import Image

ROOT = Path(__file__).resolve().parents[1]
GRIDS = {
    'home-interior-v2': (1, 1),
    'church-colonia-v1': (1, 1), 'home-campeira-exterior-v1': (1, 1),
    'agriculture-colonia-v1': ([0, 768, 1536], [0, 390, 660, 1024]),
    'home-furniture-v1': ([0, 592, 980, 1536], [0, 330, 548, 813, 1024]),
    'forge-weapons-v1': ([0, 512, 1024, 1536], [0, 490, 1024]),
    'forge-equipment-v1': ([0, 384, 768, 1152, 1536], [0, 335, 681, 1024]),
    'forge-supplies-v1': ([0, 384, 768, 1152, 1536], [0, 290, 530, 775, 1024]),
    'home-earth-materials-v1': (2, 1),
}
# A few generated objects cross the regular grid's gutter slightly.
REGIONS = {'home-furniture-v1': {
    0: (180, 0, 580, 328), 1: (620, 0, 940, 330), 2: (990, 0, 1370, 330),
    3: (170, 310, 585, 546), 4: (605, 345, 960, 560), 5: (1000, 330, 1360, 580),
    6: (225, 545, 495, 817), 7: (610, 560, 885, 790), 8: (900, 590, 1385, 795),
    9: (175, 819, 530, 1024), 10: (595, 797, 970, 1018), 11: (1020, 795, 1380, 985)},
           'forge-equipment-v1': {1: (420, 0, 765, 330), 2: (768, 0, 1152, 310),
               4: (0, 345, 394, 650), 5: (395, 345, 770, 680),
               6: (768, 310, 1152, 670), 8: (0, 670, 400, 1024),
               9: (410, 690, 775, 1024), 10: (785, 670, 1176, 1024), 11: (1177, 670, 1536, 1024)},
           'forge-supplies-v1': {4: (0, 290, 430, 530), 5: (520, 290, 700, 530),
               9: (384, 530, 768, 755), 10: (768, 530, 1152, 755), 11: (1152, 530, 1536, 755), 12: (0, 760, 384, 1024),
               13: (384, 760, 768, 1024), 14: (768, 760, 1152, 1024), 15: (1152, 760, 1536, 1024)}}
result = {}
for key, (xs, ys) in GRIDS.items():
    im = Image.open(ROOT / 'assets/images/campeira' / (key + '.png'))
    if isinstance(xs, int): xs = [round(i * im.width / xs) for i in range(xs + 1)]
    if isinstance(ys, int): ys = [round(i * im.height / ys) for i in range(ys + 1)]
    alpha = im.getchannel('A').point(lambda x: 255 if x > 90 else 0) if im.mode == 'RGBA' else None
    frames = []
    for row in range(len(ys) - 1):
        for col in range(len(xs) - 1):
            box = REGIONS.get(key, {}).get(len(frames), (xs[col], ys[row], xs[col + 1], ys[row + 1]))
            bounds = alpha.crop(box).getbbox() if alpha else (0, 0, box[2]-box[0], box[3]-box[1])
            if not bounds: raise ValueError((key, row, col))
            l, t, r, b = bounds
            frames.append([box[0]+l, box[1]+t, r-l, b-t])
    result[key] = {'width': im.width, 'height': im.height, 'frames': frames}
(ROOT / 'js/render/campeira-art-crops.js').write_text('// Generated by tools/campeira-bounds.py (alpha inspection only).\nconst CAMPEIRA_CROPS = ' + json.dumps(result, separators=(',', ':')) + ';\n', encoding='utf-8')
print('Crop metadata:', len(result), 'atlases,', sum(len(x['frames']) for x in result.values()), 'sprites')
