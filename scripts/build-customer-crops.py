"""Read alpha bounds and waist anchors; preserve the generated character PNGs."""
from pathlib import Path
import json
import numpy as np
from PIL import Image
from scipy.ndimage import label, find_objects

ROOT = Path(__file__).resolve().parents[1]
out = {}
for key in ['grazi', 'princesa', 'gaucha-chique']:
    im = Image.open(ROOT/'assets/images/expansion'/f'{key}-v1.png')
    assert im.mode == 'RGBA', (key, 'needs alpha')
    alpha = np.array(im)[:, :, 3]
    assert (alpha == 0).mean() > .2, (key, 'needs transparent background')
    ids, _ = label(alpha > 32)
    sizes = np.bincount(ids.ravel())
    boxes = []
    for n, region in enumerate(find_objects(ids), 1):
        if sizes[n] < 2200: continue
        y, x = region
        boxes.append([x.start, y.start, x.stop, y.stop])
    assert len(boxes) == 12, (key, len(boxes), 'inspect separate figures')
    boxes.sort(key=lambda b: (b[1]+b[3])/2)
    boxes = [b for row in range(3) for b in sorted(boxes[row*4:row*4+4])]
    frames = []
    for l,t,r,b in boxes:
        h = b-t
        # Anchor above the skirt hem/striding boots to prevent lateral skating.
        strip = alpha[t+int(h*.42):t+int(h*.57), l:r] > 120
        weights = strip.sum(axis=0)
        pivot = l+int(np.searchsorted(weights.cumsum(), weights.sum()/2))
        x,y = max(0,l-1),max(0,t-1)
        frames.append([x,y,min(im.width,r+1)-x,min(im.height,b+1)-y,pivot-x,b-y])
    out[key+'-v1'] = {'width':im.width,'height':im.height,'frames':frames}
(ROOT/'js/render/customer-art-crops.js').write_text(
    "// Generated by scripts/build-customer-crops.py; source PNGs stay intact.\n'use strict';\nconst CUSTOMER_ART_CROPS = "
    +json.dumps(out,separators=(',',':'))+';\n',encoding='utf-8')
print('Grazi, princesa and gaucha chique: 36 poses, alpha bounds and waist anchors')
