"""Read generated atlases and register poses/anchors, without editing source images."""
from pathlib import Path
import json
import numpy as np
from PIL import Image
from scipy.ndimage import label, find_objects

ROOT = Path(__file__).resolve().parents[1]
SHEETS = {'sadi-lanca-walk':3, 'sadi-lanca-attack':3, 'pampa-props':4,
          'pampa-npcs':4, 'pampa-fauna':4, 'pampa-tropas':6,
          'pampa-chefes':6, 'pampa-cavalaria':3, 'pampa-flora':2,
          'oficial-adaga':2, 'pampa-campo':2}
out = {}
for key, rows in SHEETS.items():
    cols = 2 if key == 'pampa-campo' else 4
    file = 'assets/images/pampa/' + key + ('-v2.png' if key == 'pampa-campo' else '-v1.png')
    im = Image.open(ROOT / file)
    assert im.mode == 'RGBA'
    alpha = np.array(im)[:, :, 3]
    assert (alpha < 10).mean() > .35
    ids, _ = label(alpha > 32)
    sizes = np.bincount(ids.ravel())
    objects = find_objects(ids)
    boxes = []
    for n, region in enumerate(objects, 1):
        if sizes[n] < 1200: continue
        y, x = region
        boxes.append([x.start, y.start, x.stop, y.stop, n])
    assert len(boxes) == rows * cols, (key, len(boxes))
    boxes.sort(key=lambda b:(b[1]+b[3])/2)
    boxes = [b for row in range(rows) for b in sorted(boxes[row*cols:row*cols+cols])]
    frames, clips = [], {}
    human = key in ['sadi-lanca-walk','sadi-lanca-attack','pampa-npcs','pampa-tropas','pampa-chefes','oficial-adaga']
    for i, (left,top,right,bottom,own) in enumerate(boxes):
        x,y,r,b = max(0,left-2), max(0,top-2), min(im.width,right+2), min(im.height,bottom+2)
        if human:
            strip = alpha[top+int((bottom-top)*.64):top+int((bottom-top)*.84),left:right] > 120
            weights = strip.sum(axis=0)
            pivot = left + int(np.searchsorted(weights.cumsum(), weights.sum()/2))
        elif key == 'pampa-campo':
            strip = alpha[top+int((bottom-top)*.86):bottom,left:right] > 120
            weights = strip.sum(axis=0)
            pivot = left + int(np.searchsorted(weights.cumsum(), weights.sum()/2))
        else: pivot = (left+right)//2
        # A few weapon rectangles overlap, but their actual silhouettes do not.
        if any(n != own and sizes[n] >= 1200 for n in np.unique(ids[y:b,x:r]) if n):
            mask = ids[y:b,x:r] == own
            a,z = [],[]
            for yy in range(mask.shape[0]):
                xs = np.flatnonzero(mask[yy])
                if not len(xs): continue
                l,rr = max(0,int(xs[0])-1), min(r-x,int(xs[-1])+2)
                a.extend([[l,yy],[l,yy+1]]); z.extend([[rr,yy],[rr,yy+1]])
            poly = []
            for point in a + z[::-1]:
                while len(poly)>1:
                    aa,bb = poly[-2:]
                    if (bb[0]-aa[0])*(point[1]-bb[1]) != (bb[1]-aa[1])*(point[0]-bb[0]): break
                    poly.pop()
                if not poly or point != poly[-1]: poly.append(point)
            clips[i] = poly
        frames.append([x,y,r-x,b-y,pivot-x,bottom-y])
    # Body heights exclude the spear above the head; the weapon never changes scale.
    reference = {'sadi-lanca-walk':282,'sadi-lanca-attack':300}.get(key,frames[0][3])
    out[key] = {'file':file,'size':list(im.size),'reference':reference,'frames':frames}
    if clips: out[key]['clips']=clips
im = Image.open(ROOT/'assets/images/pampa/pampa-stone-v2.png')
w,h=im.size
out['pampa-stone']={'file':'assets/images/pampa/pampa-stone-v2.png','size':[w,h],
    'reference':h//2,'frames':[[0,0,w,h//2,w//2,h//2],[0,h//2,w,h-h//2,w//2,h-h//2]]}
(ROOT/'js/render/pampa-art-crops.js').write_text(
    "// Generated by scripts/build-pampa-crops.py; original PNGs stay untouched.\n'use strict';\nconst PAMPA_ART_CROPS = "
    +json.dumps(out,separators=(',',':'))+';\n',encoding='utf-8')
print(sum(len(s['frames']) for s in out.values()), 'poses registered in',len(out),'atlases')
