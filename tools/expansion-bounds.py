"""Read alpha bounds only; generated source artwork is never modified."""
import json
from pathlib import Path
from PIL import Image

ROOT = Path(__file__).resolve().parents[1]
SHEETS = {
    'cave-beasts-a-v1': (4, 4), 'cave-beasts-b-v1': (4, 4),
    'cave-props-v1': (4, 3), 'sadi-combat-v1': (4, 3),
    'sadi-mounted-v1': (4, 3), 'olmiro-mounted-v1': (4, 3),
    'wild-horses-v1': (4, 3), 'padre-romio-v1': (4, 3),
    'horse-tether-v1': (1, 1),
    'secondary-common-v4': (6, 4), 'secondary-inter-v4': (6, 6),
    'secondary-gremio-v4': (6, 6), 'secondary-gremio2-v4': (6, 6),
    'dunstan-walk-v2': (4, 3), 'cave-mouth-v2': (1, 1),
    'cave-terrain-v1': (2, 2),
    'oktober-hans-v1': (4, 3), 'oktober-helga-v1': (4, 3),
    'estela-mounted-v1': (4, 3), 'ramiro-mounted-v1': (4, 3),
    'charrua-mounted-v1': (4, 3), 'saci-walk-v2': (4, 2),
    'uruguai-fish-v1': (2, 2),
}
result = {}
def main_component_bounds(mask):
    """Ignore disconnected pixels from a neighboring row; return coordinates only."""
    width, height = mask.size
    pixels = bytearray(mask.tobytes())
    best_count, best = 0, None
    for origin in range(len(pixels)):
        if not pixels[origin]:
            continue
        pixels[origin] = 0
        stack, count = [origin], 0
        left, top, right, bottom = width, height, 0, 0
        while stack:
            point = stack.pop()
            x, y = point % width, point // width
            count += 1
            left, top, right, bottom = min(left,x), min(top,y), max(right,x+1), max(bottom,y+1)
            for next_point in ((point-1 if x else -1), (point+1 if x+1<width else -1), point-width, point+width):
                if 0 <= next_point < len(pixels) and pixels[next_point]:
                    pixels[next_point] = 0
                    stack.append(next_point)
        if count > best_count:
            best_count, best = count, (left,top,right,bottom)
    return best

for name, (cols, rows) in SHEETS.items():
    im = Image.open(ROOT / 'assets/images/expansion' / (name + '.png')).convert('RGBA')
    alpha = im.getchannel('A')
    frames = []
    # Generated grids can have a slightly uneven gutter. Locate it without changing pixels.
    mask = alpha.point(lambda n: 255 if n > 80 else 0)
    def gutter(ideal, span, density, limit):
        candidates = range(max(1,round(ideal-span*.24)), min(limit-1,round(ideal+span*.24)))
        return min(candidates, key=lambda pos: (density(pos), abs(pos-ideal)))
    boundaries = [0] + [gutter(i*im.height/rows, im.height/rows,
        lambda pos: sum(mask.crop((0,pos,im.width,pos+1)).getdata())//255, im.height)
        for i in range(1,rows)] + [im.height]
    if name == 'cave-terrain-v1':
        boundaries = [round(i*im.height/rows) for i in range(rows+1)]
    for row in range(rows):
        top, end = boundaries[row], boundaries[row+1]
        columns = [0] + [gutter(i*im.width/cols, im.width/cols,
            lambda pos: sum(mask.crop((pos,top,pos+1,end)).getdata())//255, im.width)
            for i in range(1,cols)] + [im.width]
        if name == 'cave-terrain-v1': columns = [round(i*im.width/cols) for i in range(cols+1)]
        for col in range(cols):
            x, y, right, bottom = columns[col], top, columns[col+1], end
            a = alpha.crop((x, y, right, bottom)).point(lambda n: 255 if n > 80 else 0)
            box = main_component_bounds(a) if name.startswith('secondary-') else a.getbbox()
            if not box:
                raise ValueError(f'Empty frame: {name} {row},{col}')
            l, t, r, b = box
            # Anchor between the feet, not between the head and an extended weapon/tail.
            feet = a.crop((l, max(t, b - max(4, (b-t)//8)), r, b)).getbbox()
            ax = (feet[0] + feet[2]) / 2 if feet else (r-l)/2
            frames.append([x+l, y+t, r-l, b-t, round(ax), b-t])
    result[name] = {'width': im.width, 'height': im.height, 'cols': cols, 'rows': rows, 'frames': frames}
    print(name, im.size, 'alpha', alpha.getextrema(), len(frames))
(ROOT / 'js/render/expansion-art-crops.js').write_text(
    '// Generated by tools/expansion-bounds.py; coordinates only.\nconst EXPANSION_CROPS = ' + json.dumps(result, separators=(',', ':')) + ';\n', encoding='utf-8')
