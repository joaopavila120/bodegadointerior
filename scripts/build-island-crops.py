"""Read alpha bounds for island architecture. Source PNG pixels are never edited."""
from pathlib import Path
import json
import numpy as np
from PIL import Image
from scipy.ndimage import label, find_objects

ROOT = Path(__file__).resolve().parents[1]
LAYOUT = {'capela-costeira': (1,1), 'farol': (1,1), 'vila-pesqueira': (2,2),
          'forte-predios': (2,2), 'forte-muralhas': (3,2), 'entradas': (2,2),
          'masmorra-objetos': (4,2), 'objetos-costeiros': (4,2), 'masmorra-materiais': (2,2),
          'canhao-patio': (1,1)}
out = {}
for key, (cols,rows) in LAYOUT.items():
    path = ROOT / 'assets/images/island' / (key+'-v1.png')
    if not path.exists():
        continue
    im = Image.open(path)
    if key == 'masmorra-materiais':
        rects = [[c*im.width//2,r*im.height//2,im.width//2,im.height//2] for r in range(2) for c in range(2)]
    else:
        assert im.mode == 'RGBA', (key,'needs alpha')
        alpha = np.array(im)[:,:,3]
        assert (alpha == 0).mean() > .1, (key,'needs a transparent background')
        ids,_ = label(alpha > 32)
        sizes = np.bincount(ids.ravel())
        boxes=[]
        for n,region in enumerate(find_objects(ids),1):
            if sizes[n] < 1000: continue
            y,x=region; boxes.append([x.start,y.start,x.stop,y.stop])
        if key == 'masmorra-objetos':
            # The open gate is two separate jambs with transparent walk-through space.
            jambs = [b for b in boxes if 490 < b[0] < 880 and b[1] < 510]
            assert len(jambs) == 2, 'review open gate jambs'
            boxes = [b for b in boxes if b not in jambs]
            boxes.append([min(b[0] for b in jambs), min(b[1] for b in jambs),
                          max(b[2] for b in jambs), max(b[3] for b in jambs)])
        assert len(boxes)==cols*rows,(key,len(boxes),'review separated objects')
        boxes.sort(key=lambda b:(b[1]+b[3])/2)
        boxes=[b for row in range(rows) for b in sorted(boxes[row*cols:row*cols+cols])]
        rects=[]
        for l,t,r,b in boxes:
            x,y=max(0,l-1),max(0,t-1)
            rects.append([x,y,min(im.width,r+1)-x,min(im.height,b+1)-y])
    out[key]={'size':list(im.size),'rects':rects}
(ROOT/'js/render/island-architecture-crops.js').write_text(
    "// Reviewed island architecture bounds, generated by scripts/build-island-crops.py.\n'use strict';\nconst ISLAND_ATLAS = "
    +json.dumps(out,separators=(',',':'))+';\n',encoding='utf-8')
print(f'{len(out)} atlases, {sum(len(a["rects"]) for a in out.values())} objects/materials')
